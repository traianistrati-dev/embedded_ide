//! Windows: undo a Zadig / libwdi WinUSB install that took over a serial port.
//!
//! Zadig replaces the driver on ONE USB interface. Pointing it at the debug
//! interface is what makes probe-rs able to open a board; pointing it at the CDC
//! interface by mistake takes the board's COM port away, and with it flashing
//! and the serial monitor. The board then looks broken rather than
//! misconfigured, because nothing anywhere says a driver was swapped.
//!
//! Two facts make the undo exact rather than a guess:
//!
//! 1. Windows keeps the COM name on the interface (`PortName` under `Device
//!    Parameters`) even while WinUSB drives it. So the port that comes back is
//!    the SAME number — it is remembered per device, not reassigned.
//! 2. libwdi (the installer library inside Zadig) writes the target hardware id
//!    into the driver package's signer field, e.g. `USB\VID_303A&PID_1001&MI_00
//!    (libwdi autogenerated)`. That is what tells its packages apart from every
//!    other WinUSB package in the store — including libwdi's own generic one,
//!    which is signed `USB\MS_COMP_WINUSB` and must NOT be removed.
//!
//! Zadig run twice leaves two packages for the same interface. Deleting only the
//! bound one is useless: Windows immediately re-binds the leftover, both being
//! exact hardware-id matches, and the port stays gone. So every package that
//! names the interface goes, or none of it works.
//!
//! Nothing here changes a driver. It finds the mistake and builds the exact
//! `pnputil` lines that undo it; running them needs administrator rights, which
//! only the user can grant — the same arrangement as the udev rules this IDE
//! writes but never installs (see [`crate::udev`]).

use crate::build::no_window;
use std::process::Command;

/// A serial interface that a WinUSB install took over.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct HijackedPort {
    /// `USB\VID_303A&PID_1001&MI_00` — the hardware id libwdi's packages name.
    pub hardware_id: String,
    /// The COM name Windows still has on file, e.g. `COM12`.
    pub port_name: String,
    /// The driver packages to remove, e.g. `["oem136.inf", "oem133.inf"]`.
    /// Empty means the interface is hijacked but nothing in the store admits to
    /// it — see [`restore_script`], which then refuses to build a command.
    pub packages: Vec<String>,
}

impl HijackedPort {
    /// One line for a log or a card: what was lost and what took it.
    pub fn summary(&self) -> String {
        format!(
            "{} is bound to WinUSB, so {} no longer exists",
            self.hardware_id, self.port_name
        )
    }
}

/// Every serial interface of this probe that a WinUSB install took over.
///
/// Driven off the probe's own `VID:PID`, so it can only ever report on a board
/// the user is actually debugging — never on some unrelated device that someone
/// deliberately bound to WinUSB for their own reasons.
pub fn hijacked_ports(selector: &str) -> Vec<HijackedPort> {
    if !cfg!(target_os = "windows") {
        return Vec::new();
    }
    let Some((vid, pid)) = crate::probe::vid_pid(selector) else {
        return Vec::new();
    };
    let keys = crate::probe::device_keys(
        &crate::probe::reg_subkeys(crate::probe::USB_ENUM),
        &vid,
        &pid,
    );
    // Asked once, not once per interface: the store is the same for all of them.
    let store = enum_drivers();
    let mut out = Vec::new();
    for key in &keys {
        let hardware_id = match key.rsplit('\\').next() {
            Some(leaf) if !leaf.is_empty() => format!(r"USB\{leaf}"),
            _ => continue,
        };
        for inst in crate::probe::winusb_instances(&crate::probe::reg_dump(key), key) {
            // A COM name on a WinUSB-driven interface is the whole signal: a
            // port Windows still has on file, with no driver left to serve it.
            let Some(port_name) = inst.port_name else {
                continue;
            };
            out.push(HijackedPort {
                packages: packages_for(&store, &hardware_id),
                hardware_id: hardware_id.clone(),
                port_name,
            });
        }
    }
    out
}

/// The `pnputil` lines that give the port back, or `None` when there is nothing
/// safe to run.
///
/// `None` rather than a half-command: if no package in the store names this
/// interface, the binding came from somewhere this cannot identify, and a
/// guessed `/delete-driver` would remove a package that was never the problem.
pub fn restore_script(port: &HijackedPort) -> Option<String> {
    if port.packages.is_empty() {
        return None;
    }
    let mut lines: Vec<String> = port
        .packages
        .iter()
        .map(|p| format!("pnputil /delete-driver {p} /uninstall /force"))
        .collect();
    // Without this the device sits driverless until the next replug.
    lines.push("pnputil /scan-devices".to_string());
    Some(lines.join("\n"))
}

/// Run the restore with administrator rights, through Windows' own consent
/// dialog. `Ok` only once `pnputil` has actually run and exited 0.
///
/// One elevation for the whole script: a prompt per package would train the user
/// to click through them, which is the opposite of informed consent. Declining
/// the prompt is reported as the ordinary outcome it is, not as a failure.
pub fn run_elevated(script: &str) -> Result<String, String> {
    // Every token in the script came out of `packages_for`, which accepts only
    // `oem<digits>.inf` — so nothing here can carry a quote into PowerShell.
    let inner = script.replace('\n', "; ");
    let ps = format!(
        "$ErrorActionPreference='Stop'; \
         $p = Start-Process powershell -Verb RunAs -Wait -PassThru \
         -ArgumentList '-NoProfile','-Command','{inner}'; exit $p.ExitCode"
    );
    let out = no_window(&mut Command::new("powershell"))
        .args(["-NoProfile", "-NonInteractive", "-Command", &ps])
        .output()
        .map_err(|e| format!("could not start PowerShell: {e}"))?;
    if out.status.success() {
        return Ok(String::from_utf8_lossy(&out.stdout).trim().to_string());
    }
    let err = String::from_utf8_lossy(&out.stderr);
    if err.contains("canceled") || err.contains("cancelled") {
        return Err("the Windows elevation prompt was declined — nothing changed".to_string());
    }
    Err(format!(
        "pnputil did not complete: {}",
        err.lines()
            .map(str::trim)
            .find(|l| !l.is_empty())
            .unwrap_or("no output")
    ))
}

/// `pnputil /enum-drivers` as text, empty when it cannot be asked.
fn enum_drivers() -> String {
    no_window(&mut Command::new("pnputil"))
        .args(["/enum-drivers"])
        .output()
        .map(|o| String::from_utf8_lossy(&o.stdout).into_owned())
        .unwrap_or_default()
}

/// The driver packages in the store that libwdi built for one hardware id.
///
/// Parsed by VALUE, never by label: `pnputil` prints its field names in the
/// language Windows is installed in, so "Provider Name:" is not something to
/// match on. `oem<digits>.inf`, the string `libwdi` and the hardware id are the
/// same in every language.
pub(crate) fn packages_for(enum_drivers: &str, hardware_id: &str) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    let want = hardware_id.to_ascii_lowercase();
    let mut take = |block: &[&str]| {
        let lower = block.join(" ").to_ascii_lowercase();
        if !lower.contains("libwdi") || !lower.contains(&want) {
            return;
        }
        if let Some(inf) = block.iter().find_map(|l| oem_inf(l))
            && !out.contains(&inf)
        {
            out.push(inf);
        }
    };
    // Records are separated by a BLANK LINE, gathered line by line rather than
    // by splitting on "\n\n": `pnputil` writes CRLF, so that split finds no
    // separator at all and hands the whole store back as one record - which
    // then matches on some other package's libwdi and names the wrong .inf.
    let mut block: Vec<&str> = Vec::new();
    for line in enum_drivers.lines() {
        if line.trim().is_empty() {
            take(&block);
            block.clear();
        } else {
            block.push(line);
        }
    }
    take(&block);
    out
}

/// The `oem<digits>.inf` name in one `pnputil` record, lowercased.
///
/// The shape is the validation: the result is pasted into a command line, and
/// only this exact form — letters `oem`, digits, `.inf` — can come out.
fn oem_inf(block: &str) -> Option<String> {
    block
        .split_whitespace()
        .find(|w| {
            w.is_ascii()
                && w.len() > 7
                && w.get(..3).is_some_and(|p| p.eq_ignore_ascii_case("oem"))
                && w[w.len() - 4..].eq_ignore_ascii_case(".inf")
                && w[3..w.len() - 4].chars().all(|c| c.is_ascii_digit())
        })
        .map(str::to_ascii_lowercase)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Verbatim `pnputil /enum-drivers` records from the bench, where Zadig had
    /// been run TWICE on the ESP32-C3's serial interface, plus two packages that
    /// must survive: libwdi's generic one and an unrelated vendor driver.
    const STORE: &str = "\
Published Name:     oem57.inf\n\
Original Name:      cpsups.inf\n\
Provider Name:      CyberPower\n\
Class Name:         Batteries\n\
Signer Name:        Microsoft Windows Hardware Compatibility Publisher\n\
\n\
Published Name:     oem136.inf\n\
Original Name:      usb_jtagserial_debug_unit_(interface_0).inf\n\
Provider Name:      libwdi\n\
Class Name:         Universal Serial Bus devices\n\
Signer Name:        USB\\VID_303A&PID_1001&MI_00 (libwdi autogenerated)\n\
\n\
Published Name:     oem133.inf\n\
Original Name:      usb_jtagserial_debug_unit_(interface_0).inf\n\
Provider Name:      libwdi\n\
Class Name:         Universal Serial Bus devices\n\
Signer Name:        USB\\VID_303A&PID_1001&MI_00 (libwdi autogenerated)\n\
\n\
Published Name:     oem16.inf\n\
Original Name:      winusb_generic_device.inf\n\
Provider Name:      libwdi\n\
Class Name:         Universal Serial Bus devices\n\
Signer Name:        USB\\MS_COMP_WINUSB (libwdi autogenerated)\n\
\n\
Published Name:     oem64.inf\n\
Original Name:      stlink_winusb.inf\n\
Provider Name:      libwdi\n\
Class Name:         Universal Serial Bus devices\n\
Signer Name:        USB\\VID_0483&PID_3748 (libwdi autogenerated)\n";

    #[test]
    fn both_copies_of_the_offending_package_are_found() {
        // Zadig run twice leaves two. Removing one and not the other achieves
        // nothing: Windows re-binds the leftover and the port stays gone.
        let found = packages_for(STORE, r"USB\VID_303A&PID_1001&MI_00");
        assert_eq!(found, vec!["oem136.inf", "oem133.inf"]);
    }

    #[test]
    fn other_peoples_drivers_are_left_alone() {
        // The generic libwdi package and the ST-Link's own are both libwdi and
        // both WinUSB; only the hardware id keeps them out of the command.
        let found = packages_for(STORE, r"USB\VID_303A&PID_1001&MI_00");
        for spared in ["oem16.inf", "oem64.inf", "oem57.inf"] {
            assert!(
                !found.contains(&spared.to_string()),
                "{spared} would be deleted"
            );
        }
    }

    #[test]
    fn a_different_interface_of_the_same_board_is_a_different_package() {
        // MI_02 is the JTAG half. Undoing the serial mistake must not touch a
        // driver the user may have installed there ON PURPOSE.
        assert!(packages_for(STORE, r"USB\VID_303A&PID_1001&MI_02").is_empty());
    }

    #[test]
    fn the_real_crlf_output_splits_into_records() {
        // `pnputil` writes CRLF. Splitting on "\n\n" finds no separator there,
        // so the whole store reads as ONE record and the first `oem*.inf` in it
        // - somebody else's driver - comes back as the one to delete.
        let crlf = STORE.replace('\n', "\r\n");
        assert_eq!(
            packages_for(&crlf, r"USB\VID_303A&PID_1001&MI_00"),
            vec!["oem136.inf", "oem133.inf"],
            "CRLF output must parse the same as LF"
        );
        // The proof it is really splitting: the first record in the store is a
        // battery driver, and it must never be the answer.
        assert!(
            !packages_for(&crlf, r"USB\VID_303A&PID_1001&MI_00").contains(&"oem57.inf".to_string())
        );
    }

    #[test]
    fn a_localised_pnputil_still_parses() {
        // The field labels are translated; the values are not. Matching on
        // "Provider Name:" would find nothing on a German or Romanian Windows.
        let german = STORE
            .replace("Published Name:", "Veröffentlichter Name:")
            .replace("Provider Name:", "Anbietername:")
            .replace("Signer Name:", "Signaturgebername:");
        assert_eq!(
            packages_for(&german, r"USB\VID_303A&PID_1001&MI_00"),
            vec!["oem136.inf", "oem133.inf"]
        );
    }

    #[test]
    fn the_script_removes_every_copy_then_rescans() {
        let port = HijackedPort {
            hardware_id: r"USB\VID_303A&PID_1001&MI_00".to_string(),
            port_name: "COM12".to_string(),
            packages: vec!["oem136.inf".into(), "oem133.inf".into()],
        };
        let script = restore_script(&port).expect("a command");
        assert_eq!(
            script,
            "pnputil /delete-driver oem136.inf /uninstall /force\n\
             pnputil /delete-driver oem133.inf /uninstall /force\n\
             pnputil /scan-devices"
        );
        assert!(port.summary().contains("COM12"), "{}", port.summary());
    }

    #[test]
    fn nothing_to_remove_produces_no_command_at_all() {
        // A hijack this cannot attribute to a package in the store. Guessing a
        // `/delete-driver` here would remove a driver that was never at fault.
        let port = HijackedPort {
            hardware_id: r"USB\VID_1234&PID_5678&MI_00".to_string(),
            port_name: "COM3".to_string(),
            packages: Vec::new(),
        };
        assert!(restore_script(&port).is_none());
    }

    #[test]
    fn only_an_oem_inf_shape_can_reach_a_command_line() {
        // The script is interpolated into a PowerShell single-quoted string, so
        // this shape check is what makes that safe.
        assert_eq!(
            oem_inf("Published Name: oem136.inf").as_deref(),
            Some("oem136.inf")
        );
        assert_eq!(oem_inf("Original Name: usb_thing_(interface_0).inf"), None);
        assert_eq!(oem_inf("oem.inf"), None, "no digits");
        assert_eq!(oem_inf("oem12x.inf"), None, "not all digits");
        assert_eq!(oem_inf("'; rm -rf /; '.inf"), None, "not an oem name");
    }
}
