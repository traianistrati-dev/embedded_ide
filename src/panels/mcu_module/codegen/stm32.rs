//! STM32 code generation — HAL code building, section splicing, pin parsing.

use super::super::clock::frequencies;
use super::super::clock::model::{ClockConfig, PllSrc, Stm32f1Clock, SysclkSrc};
use super::super::pins::logic::pin::Pin;
use super::super::pins::logic::pin_function::PinFunction;
use super::{mcu_id_marker_line, GEN_BEGIN, GEN_END, USER_TAIL};
use std::collections::{BTreeMap, BTreeSet};

// ── Section splicing ──────────────────────────────────────────────────────────

pub fn splice_section(existing: &str, new_section: &str, mcu_name: &str, mcu_id: &str) -> String {
    if let (Some(begin), Some(end_start)) = (existing.find(GEN_BEGIN), existing.find(GEN_END)) {
        let end = end_start + GEN_END.len();
        // Strip ALL leading newlines after GEN_END, then re-add exactly one
        // blank line.  This makes splice idempotent: running it N times always
        // produces the same result instead of accumulating newlines.
        let after = existing[end..].trim_start_matches('\n');

        // Detect old format (had fn custom_config / fn loop_code after GEN_END).
        // Rebuild from scratch so the user tail is the new flat loop{} style.
        if after.contains("fn custom_config()") || after.contains("fn loop_code()") {
            return format!(
                "{}{}\n{}",
                invariant_header(mcu_name, mcu_id),
                new_section,
                USER_TAIL,
            );
        }

        // new_section already ends with "// <<< GENERATED END >>>\n"
        // + one more "\n" gives a single blank line before the user tail.
        format!("{}{}\n{}", &existing[..begin], new_section, after)
    } else {
        // Markers not found — rebuild from scratch.
        format!(
            "{}{}\n{}",
            invariant_header(mcu_name, mcu_id),
            new_section,
            USER_TAIL,
        )
    }
}

// ── Invariant file header ─────────────────────────────────────────────────────

pub fn invariant_header(mcu_name: &str, mcu_id: &str) -> String {
    format!(
        "// Auto-generated by Embedded IDE\n\
         // MCU: {mcu_name} | HAL: stm32f1xx-hal\n\
         {id}\n\
         #![no_std]\n\
         #![no_main]\n\n\
         pub mod pins;\n\n\
         use panic_halt as _;\n\
         use cortex_m_rt::entry;\n\n",
        id = mcu_id_marker_line(mcu_id),
    )
}

// ── Clock setup (rcc.cfgr chain) ──────────────────────────────────────────────

/// Format a Hz value as a stm32f1xx-hal rate literal (`72.MHz()`, `48.kHz()`…).
fn freq_lit(hz: u32) -> String {
    if hz % 1_000_000 == 0 {
        format!("{}.MHz()", hz / 1_000_000)
    } else if hz % 1_000 == 0 {
        format!("{}.kHz()", hz / 1_000)
    } else {
        format!("{hz}.Hz()")
    }
}

/// Build the `rcc.cfgr … .freeze(&mut flash.acr)` chain from the clock config.
///
/// Only knobs that deviate from the HAL's natural defaults are emitted, so the
/// default 72 MHz config produces exactly the original
/// `use_hse(8).sysclk(72).pclk1(36)` chain (no spurious diffs).
pub fn clock_setup_chain(clock: &ClockConfig) -> String {
    let c: Stm32f1Clock = match clock {
        // The graph is the only clock model — read its node states back into
        // the typed codegen intermediate.
        ClockConfig::Graph(gc) => {
            crate::panels::mcu_module::clock::graph::graph_to_stm32f1(&gc.graph)
        }
        ClockConfig::None => Stm32f1Clock::default(),
    };
    let f = frequencies(&c);
    // Newline + 17 spaces → lines up the `.method()` calls under `rcc.cfgr`.
    const IND: &str = "\n                 ";

    let mut s = String::from("rcc.cfgr");
    let use_hse = c.hse_enabled
        && (c.sysclk_src == SysclkSrc::Hse
            || (c.sysclk_src == SysclkSrc::Pll
                && matches!(c.pll_src, PllSrc::Hse | PllSrc::HseDiv2)));
    if use_hse {
        s.push_str(&format!("{IND}.use_hse({})", freq_lit(c.hse_hz)));
    }
    s.push_str(&format!("{IND}.sysclk({})", freq_lit(f.sysclk)));
    s.push_str(&format!("{IND}.pclk1({})", freq_lit(f.pclk1)));
    if c.ahb_pre != 1 {
        s.push_str(&format!("{IND}.hclk({})", freq_lit(f.hclk)));
    }
    if c.apb2_pre != 1 {
        s.push_str(&format!("{IND}.pclk2({})", freq_lit(f.pclk2)));
    }
    if c.adc_pre != 6 {
        s.push_str(&format!("{IND}.adcclk({})", freq_lit(f.adcclk)));
    }
    s.push_str(&format!("{IND}.freeze(&mut flash.acr)"));
    s
}

/// Machine-readable clock marker line, parsed back on project open so the Clock
/// tab restores exactly (target-frequency code alone is ambiguous).
fn clock_comment_line(clock: &ClockConfig) -> String {
    let c = match clock {
        ClockConfig::Graph(gc) => {
            crate::panels::mcu_module::clock::graph::graph_to_stm32f1(&gc.graph)
        }
        ClockConfig::None => Stm32f1Clock::default(),
    };
    crate::panels::mcu_module::clock::persist::to_comment(&c)
}

// ── Generated section builder ─────────────────────────────────────────────────

pub fn make_generated_section(mcu_name: &str, all_pins: &[&Pin], clock: &ClockConfig) -> String {
    let configured: Vec<(&Pin, PinMeta)> = all_pins
        .iter()
        .filter(|p| !p.reserved && p.selected_function != PinFunction::Unset)
        .filter_map(|p| parse_pin(&p.name).map(|m| (*p, m)))
        .collect();

    if configured.is_empty() {
        return make_default_gen_section(mcu_name, clock);
    }

    // ── Ports used ───────────────────────────────────────────────────────────
    let mut ports_used: BTreeSet<char> = BTreeSet::new();
    for (_, meta) in &configured {
        ports_used.insert(meta.port);
    }

    // ── Feature flags ────────────────────────────────────────────────────────
    let has_serial = configured.iter().any(|(p, _)| {
        matches!(
            p.selected_function,
            PinFunction::UsartTx(_) | PinFunction::UsartRx(_)
        )
    });
    let has_spi = configured.iter().any(|(p, _)| {
        matches!(
            p.selected_function,
            PinFunction::SpiSck(_) | PinFunction::SpiMosi(_)
        )
    });
    let has_i2c = configured.iter().any(|(p, _)| {
        matches!(
            p.selected_function,
            PinFunction::I2cScl(_) | PinFunction::I2cSda(_)
        )
    });
    let has_adc = configured
        .iter()
        .any(|(p, _)| matches!(p.selected_function, PinFunction::AdcChannel { .. }));
    let has_timer = configured
        .iter()
        .any(|(p, _)| matches!(p.selected_function, PinFunction::TimerPwm { .. }));
    let needs_afio = has_serial || has_spi || has_i2c || has_timer;
    let has_periph_fns = has_serial || has_spi || has_i2c || has_adc;

    // ── SPI instances ────────────────────────────────────────────────────────
    let mut spi_instances: BTreeSet<u8> = BTreeSet::new();
    for (pin, _) in &configured {
        match pin.selected_function {
            PinFunction::SpiSck(n)
            | PinFunction::SpiMosi(n)
            | PinFunction::SpiMiso(n)
            | PinFunction::SpiNss(n) => {
                spi_instances.insert(n);
            }
            _ => {}
        }
    }

    // ── HAL use block ────────────────────────────────────────────────────────
    let mut use_items: Vec<String> = vec!["pac".into(), "prelude::*".into()];
    if has_periph_fns || needs_afio {
        if needs_afio {
            use_items.push("afio".into());
        }
        use_items.push("rcc::Clocks".into());
    }
    if has_serial {
        use_items.push("serial::{self, Config, Serial}".into());
    }
    if has_spi {
        let remaps = spi_instances
            .iter()
            .map(|n| format!("Spi{n}NoRemap"))
            .collect::<Vec<_>>()
            .join(", ");
        use_items.push(format!(
            "spi::{{self, Mode, Phase, Polarity, Spi, {remaps}}}"
        ));
    }
    if has_i2c {
        use_items.push("i2c::{self, BlockingI2c, Mode as I2cMode}".into());
    }
    if has_adc {
        use_items.push("adc".into());
    }
    if has_timer {
        use_items.push("timer::Timer".into());
    }

    let use_block = use_items
        .iter()
        .map(|s| format!("    {s},"))
        .collect::<Vec<_>>()
        .join("\n");

    // ── Pin declaration lines ────────────────────────────────────────────────
    let mut port_groups: BTreeMap<char, Vec<String>> = BTreeMap::new();
    for (pin, meta) in &configured {
        let expr = into_expr(&pin.selected_function, &meta.port_var, meta.crx);
        let comment = pin.selected_function.label();
        let line = if is_comment_expr(&expr) {
            format!(
                "    // {}: {}",
                pin.name,
                expr.trim_start_matches("//").trim()
            )
        } else {
            let prefix = if needs_mut_ref(&pin.selected_function) { "&mut " } else { "" };
            format!(
                "    let {var} = {prefix}{pv}.{var}.{expr}; // {comment}",
                var = meta.var,
                pv = meta.port_var,
            )
        };
        port_groups.entry(meta.port).or_default().push(line);
    }

    let mut pin_section = String::new();
    for (port, lines) in &port_groups {
        pin_section.push_str(&format!("    // ── Port {port} ──\n"));
        for l in lines {
            pin_section.push_str(l);
            pin_section.push('\n');
        }
        pin_section.push('\n');
    }

    // Peripheral helper functions (init_usartN, init_spiN, init_i2cN,
    // init_adc1) are NO LONGER emitted inside this generated block. They are
    // placed in the editable region AFTER `fn main` (see `helper_defs` /
    // `ensure_helper_defs`) so the user can tweak them. `fn_calls` below still
    // references them by name.

    // ── Peripheral init calls (inside fn main) ───────────────────────────────
    let mut fn_calls = String::new();
    let mut any_call = false;

    macro_rules! header {
        () => {
            if !any_call {
                fn_calls.push_str("    // ── Peripheral initialisation ──\n");
                any_call = true;
            }
        };
    }

    for n in 1u8..=3 {
        let tx = configured
            .iter()
            .find(|(p, _)| p.selected_function == PinFunction::UsartTx(n));
        let rx = configured
            .iter()
            .find(|(p, _)| p.selected_function == PinFunction::UsartRx(n));
        if tx.is_none() && rx.is_none() {
            continue;
        }
        header!();
        let tx_v = tx
            .map(|(_, m)| m.var.clone())
            .unwrap_or_else(|| format!("_tx{n}"));
        let rx_v = rx
            .map(|(_, m)| m.var.clone())
            .unwrap_or_else(|| format!("_rx{n}"));
        fn_calls.push_str(&format!(
            "    let (mut _tx{n}, mut _rx{n}) = \
             init_usart{n}(dp.USART{n}, ({tx_v}, {rx_v}), &mut afio, &clocks);\n"
        ));
    }

    for n in 1u8..=2 {
        let sck = configured
            .iter()
            .find(|(p, _)| p.selected_function == PinFunction::SpiSck(n));
        let miso = configured
            .iter()
            .find(|(p, _)| p.selected_function == PinFunction::SpiMiso(n));
        let mosi = configured
            .iter()
            .find(|(p, _)| p.selected_function == PinFunction::SpiMosi(n));
        if sck.is_none() && mosi.is_none() {
            continue;
        }
        header!();
        let sck_v = sck
            .map(|(_, m)| m.var.clone())
            .unwrap_or_else(|| format!("_sck{n}"));
        let miso_v = miso
            .map(|(_, m)| m.var.clone())
            .unwrap_or_else(|| format!("_miso{n}"));
        let mosi_v = mosi
            .map(|(_, m)| m.var.clone())
            .unwrap_or_else(|| format!("_mosi{n}"));
        fn_calls.push_str(&format!(
            "    let _spi{n} = \
             init_spi{n}(dp.SPI{n}, ({sck_v}, {miso_v}, {mosi_v}), &mut afio, &clocks);\n"
        ));
    }

    for n in 1u8..=2 {
        let scl = configured
            .iter()
            .find(|(p, _)| p.selected_function == PinFunction::I2cScl(n));
        let sda = configured
            .iter()
            .find(|(p, _)| p.selected_function == PinFunction::I2cSda(n));
        if scl.is_none() || sda.is_none() {
            continue;
        }
        header!();
        let scl_v = scl.unwrap().1.var.clone();
        let sda_v = sda.unwrap().1.var.clone();
        fn_calls.push_str(&format!(
            "    let _i2c{n} = \
             init_i2c{n}(dp.I2C{n}, ({scl_v}, {sda_v}), &mut afio, &clocks);\n"
        ));
    }

    if has_adc {
        header!();
        fn_calls.push_str("    let mut _adc1 = init_adc1(dp.ADC1, clocks);\n");
        for (_, meta) in configured
            .iter()
            .filter(|(p, _)| matches!(p.selected_function, PinFunction::AdcChannel { .. }))
        {
            fn_calls.push_str(&format!(
                "    // let val: u16 = _adc1.read(&mut {}).unwrap();\n",
                meta.var
            ));
        }
    }

    if has_timer {
        header!();
        fn_calls.push_str("    // ── Timers / PWM ──\n");
        fn_calls.push_str("    // let pwm = Timer::tim2(dp.TIM2, &clocks)\n");
        fn_calls.push_str(
            "    //     .pwm_hz::<Tim2NoRemap, _, _>((pa0, pa1), &mut afio.mapr, 1.kHz());\n",
        );
    }

    let can_rx = configured
        .iter()
        .find(|(p, _)| p.selected_function == PinFunction::CanRx);
    let can_tx_pin = configured
        .iter()
        .find(|(p, _)| p.selected_function == PinFunction::CanTx);
    if can_rx.is_some() || can_tx_pin.is_some() {
        header!();
        let rx_v = can_rx
            .map(|(_, m)| m.var.clone())
            .unwrap_or("_can_rx".into());
        let tx_v = can_tx_pin
            .map(|(_, m)| m.var.clone())
            .unwrap_or("_can_tx".into());
        fn_calls.push_str("    // ── CAN ──\n");
        fn_calls.push_str(&format!(
            "    // let _can = Can::new(dp.CAN1, ({rx_v}, {tx_v})); // needs bxcan crate\n"
        ));
    }

    if any_call {
        fn_calls.push('\n');
    }

    // ── Assemble port splits ─────────────────────────────────────────────────
    let port_splits = ports_used
        .iter()
        .map(|p| {
            let lc = p.to_ascii_lowercase();
            format!("    let mut gpio{lc} = dp.GPIO{p}.split();")
        })
        .collect::<Vec<_>>()
        .join("\n");

    let afio_line = if needs_afio {
        "    let mut afio = dp.AFIO.constrain();\n"
    } else {
        ""
    };

    // ── Clock setup chain (from the Clock tab config) ────────────────────────
    let clock_chain = clock_setup_chain(clock);
    let clock_comment = clock_comment_line(clock);

    // ── Put it all together ──────────────────────────────────────────────────
    // Helper fns are appended after `fn main` by `ensure_helper_defs`.
    format!(
        "{GEN_BEGIN}\n\
         {clock_comment}\n\
         use stm32f1xx_hal::{{\n\
         {use_block}\n\
         }};\n\n\
         #[entry]\n\
         fn main() -> ! {{\n\
             let dp = pac::Peripherals::take().unwrap();\n\n\
             let mut flash = dp.FLASH.constrain();\n\
             let rcc = dp.RCC.constrain();\n\
         {afio_line}\
             let clocks = {clock_chain};\n\n\
         {port_splits}\n\n\
         {pin_section}\
         {fn_calls}\
         {GEN_END}\n"
    )
}

// ── Default generated section (no pins configured yet) ────────────────────────

fn make_default_gen_section(mcu_name: &str, clock: &ClockConfig) -> String {
    let clock_chain = clock_setup_chain(clock);
    let clock_comment = clock_comment_line(clock);
    format!(
        "{GEN_BEGIN}\n\
         // MCU: {mcu_name}\n\
         {clock_comment}\n\
         use stm32f1xx_hal::{{pac, prelude::*}};\n\n\
         #[entry]\n\
         fn main() -> ! {{\n\
             let dp = pac::Peripherals::take().unwrap();\n\n\
             let mut flash = dp.FLASH.constrain();\n\
             let rcc = dp.RCC.constrain();\n\
             let _clocks = {clock_chain};\n\n\
             // Select pins in the MCU Configurator to generate code here.\n\
         {GEN_END}\n"
    )
}

// ── Editable peripheral init helpers (placed after `fn main`) ─────────────────

/// Peripheral init helper functions needed for the configured peripherals.
/// Each entry is `(fn_name, full_definition)`. These live in the user-editable
/// region **after `fn main`** (added additively by [`ensure_helper_defs`]) so
/// the user can customise them (baud rate, SPI mode, ADC sample time…) without
/// regeneration clobbering their edits. The generated `fn_calls` inside `main`
/// reference them by name; their imports come from the generated `use` block.
pub fn helper_defs(all_pins: &[&Pin]) -> Vec<(String, String)> {
    let funcs: Vec<&PinFunction> = all_pins
        .iter()
        .filter(|p| !p.reserved && p.selected_function != PinFunction::Unset)
        .map(|p| &p.selected_function)
        .collect();
    let has = |want: PinFunction| funcs.iter().any(|f| **f == want);

    let mut defs: Vec<(String, String)> = Vec::new();

    for n in 1u8..=3 {
        if has(PinFunction::UsartTx(n)) || has(PinFunction::UsartRx(n)) {
            defs.push((
                format!("init_usart{n}"),
                format!(
                    "fn init_usart{n}(
    usart:  pac::USART{n},
    pins:   impl serial::Pins<pac::USART{n}>,
    afio:   &mut afio::Parts,
    clocks: &Clocks,
) -> (serial::Tx<pac::USART{n}>, serial::Rx<pac::USART{n}>) {{
    Serial::new(
        usart,
        pins,
        &mut afio.mapr,
        Config::default().baudrate(115_200.bps()),
        clocks,
    )
    .split()
}}"
                ),
            ));
        }
    }

    for n in 1u8..=2 {
        if has(PinFunction::SpiSck(n)) || has(PinFunction::SpiMosi(n)) {
            let remap = format!("Spi{n}NoRemap");
            defs.push((
                format!("init_spi{n}"),
                format!(
                    "fn init_spi{n}<PINS>(
    spi:    pac::SPI{n},
    pins:   PINS,
    afio:   &mut afio::Parts,
    clocks: &Clocks,
) -> Spi<pac::SPI{n}, {remap}, PINS>
where
    PINS: spi::Pins<{remap}>,
{{
    Spi::spi{n}(
        spi,
        pins,
        &mut afio.mapr,
        Mode {{
            polarity: Polarity::IdleLow,
            phase: Phase::CaptureOnFirstTransition,
        }},
        1.MHz(),
        clocks,
    )
}}"
                ),
            ));
        }
    }

    for n in 1u8..=2 {
        if has(PinFunction::I2cScl(n)) && has(PinFunction::I2cSda(n)) {
            defs.push((
                format!("init_i2c{n}"),
                format!(
                    "fn init_i2c{n}<PINS>(
    i2c:    pac::I2C{n},
    pins:   PINS,
    afio:   &mut afio::Parts,
    clocks: &Clocks,
) -> BlockingI2c<pac::I2C{n}, PINS>
where
    PINS: i2c::Pins<pac::I2C{n}>,
{{
    BlockingI2c::i2c{n}(
        i2c,
        pins,
        &mut afio.mapr,
        I2cMode::Standard {{ frequency: 100_000.Hz() }},
        clocks,
        1000, 10, 1000, 1000,
    )
}}"
                ),
            ));
        }
    }

    // ADC — `Adc::adc1` takes `Clocks` BY VALUE (Clocks is Copy), not `&Clocks`.
    if funcs
        .iter()
        .any(|f| matches!(f, PinFunction::AdcChannel { .. }))
    {
        defs.push((
            "init_adc1".to_string(),
            "fn init_adc1(adc1: pac::ADC1, clocks: Clocks) -> adc::Adc<pac::ADC1> {
    adc::Adc::adc1(adc1, clocks)
}"
            .to_string(),
        ));
    }

    defs
}

/// Append any **missing** helper functions to `file`, after `fn main`, in the
/// user-editable region. Helpers already present (matched by `fn <name>(`) are
/// left untouched so user edits survive every regeneration — only brand-new
/// ones are appended. A section header is inserted once.
pub fn ensure_helper_defs(mut file: String, all_pins: &[&Pin]) -> String {
    let defs = helper_defs(all_pins);
    // A helper is "present" if its `fn <name>` is followed by either `(` (plain
    // fns like `init_adc1`) or `<` (generic fns like `init_spi1<PINS>` /
    // `init_i2c1<PINS>`). Checking only `(` missed the generic ones, so they
    // were re-appended on every regen — the infinite-growth bug.
    let missing: Vec<&(String, String)> = defs
        .iter()
        .filter(|(name, _)| {
            !(file.contains(&format!("fn {name}("))
                || file.contains(&format!("fn {name}<")))
        })
        .collect();
    if missing.is_empty() {
        return file;
    }

    if !file.ends_with('\n') {
        file.push('\n');
    }
    if !file.contains("── Peripheral init helpers") {
        file.push_str(
            "\n// ── Peripheral init helpers (editable — tweak as needed) ────────────────\n",
        );
    }
    for (_, def) in missing {
        file.push('\n');
        file.push_str(def);
        file.push('\n');
    }
    file
}

// ── Pin helpers ───────────────────────────────────────────────────────────────

struct PinMeta {
    port: char,
    pin_num: u8,
    var: String,
    port_var: String,
    crx: &'static str,
}

fn parse_pin(name: &str) -> Option<PinMeta> {
    let bytes = name.as_bytes();
    if bytes.len() < 3 || bytes[0] != b'P' {
        return None;
    }
    let port = bytes[1] as char;
    if !port.is_ascii_uppercase() {
        return None;
    }
    let pin_num: u8 = name[2..].parse().ok()?;
    let lc = port.to_ascii_lowercase();
    Some(PinMeta {
        port,
        pin_num,
        var: format!("p{}{}", lc, pin_num),
        port_var: format!("gpio{}", lc),
        crx: if pin_num < 8 { "crl" } else { "crh" },
    })
}

fn into_expr(func: &PinFunction, pv: &str, crx: &str) -> String {
    match func {
        PinFunction::GpioInput => format!("into_floating_input(&mut {pv}.{crx})"),
        PinFunction::GpioOutput => format!("into_push_pull_output(&mut {pv}.{crx})"),
        PinFunction::AdcChannel { .. } => format!("into_analog(&mut {pv}.{crx})"),
        PinFunction::TimerPwm { .. } => format!("into_alternate_push_pull(&mut {pv}.{crx})"),
        PinFunction::UsartTx(_) | PinFunction::UsartCk(_) => {
            format!("into_alternate_push_pull(&mut {pv}.{crx})")
        }
        PinFunction::UsartRx(_) | PinFunction::UsartCts(_) => {
            format!("into_floating_input(&mut {pv}.{crx})")
        }
        PinFunction::UsartRts(_) => format!("into_push_pull_output(&mut {pv}.{crx})"),
        PinFunction::SpiSck(_) | PinFunction::SpiMosi(_) => {
            format!("into_alternate_push_pull(&mut {pv}.{crx})")
        }
        PinFunction::SpiNss(_) => format!("into_push_pull_output(&mut {pv}.{crx})"),
        PinFunction::SpiMiso(_) => format!("into_floating_input(&mut {pv}.{crx})"),
        PinFunction::I2cScl(_) | PinFunction::I2cSda(_) => {
            format!("into_alternate_open_drain(&mut {pv}.{crx})")
        }
        PinFunction::Mco => format!("into_alternate_push_pull(&mut {pv}.{crx})"),
        PinFunction::CanTx => format!("into_alternate_push_pull(&mut {pv}.{crx})"),
        PinFunction::CanRx => format!("into_floating_input(&mut {pv}.{crx})"),
        PinFunction::UsbDm | PinFunction::UsbDp => {
            "// USB — configured automatically by the USB peripheral".to_owned()
        }
        PinFunction::SwdIo | PinFunction::SwdClk => {
            "// SWD — active by default, no config needed".to_owned()
        }
        PinFunction::Unset => unreachable!(),
    }
}

fn is_comment_expr(expr: &str) -> bool {
    expr.trim_start().starts_with("//")
}

/// Returns `true` for pins that are driven (output / alternate-output).
/// These get a `&mut` prefix so the binding is immediately usable as a
/// mutable reference without a later `&mut var` at each call site.
fn needs_mut_ref(func: &PinFunction) -> bool {
    matches!(
        func,
        PinFunction::GpioOutput
            | PinFunction::TimerPwm { .. }
            | PinFunction::UsartTx(_)
            | PinFunction::UsartCk(_)
            | PinFunction::UsartRts(_)
            | PinFunction::SpiSck(_)
            | PinFunction::SpiMosi(_)
            | PinFunction::SpiNss(_)
            | PinFunction::I2cScl(_)
            | PinFunction::I2cSda(_)
            | PinFunction::Mco
            | PinFunction::CanTx
    )
}
